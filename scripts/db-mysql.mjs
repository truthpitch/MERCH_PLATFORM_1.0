#!/usr/bin/env node
/**
 * Keeps the MySQL schema + migrations in step with prisma/schema.prisma.
 *
 *   node scripts/db-mysql.mjs sync                 → regenerate prisma/mysql/schema.prisma
 *   node scripts/db-mysql.mjs migration <name>     → sync, then write a new MySQL migration
 *                                                    (diff vs. the last snapshot — no MySQL server needed)
 *
 * Run `migration` every time you add a SQLite migration with `npm run db:migrate`.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const src = path.join(root, "prisma", "schema.prisma");
const dir = path.join(root, "prisma", "mysql");
const out = path.join(dir, "schema.prisma");
const snapshot = path.join(dir, "schema.snapshot.prisma");
const migrations = path.join(dir, "migrations");

function sync() {
  let schema = readFileSync(src, "utf8");
  schema = schema
    .replace('provider = "sqlite"', 'provider = "mysql"')
    .replace('output   = "../generated/prisma"', 'output   = "../../generated/prisma"')
    // `// @text` markers → real MySQL TEXT columns
    .replace(/^(\s*\w+\s+String\??)(\s*)\/\/ @text\s*$/gm, "$1 @db.Text");
  const header =
    "// GENERATED from prisma/schema.prisma by scripts/db-mysql.mjs — do not edit by hand.\n\n";
  mkdirSync(dir, { recursive: true });
  writeFileSync(out, header + schema.replace(/^\/\/ TruthPitch[\s\S]*?(?=generator)/, ""));
  console.log("✓ wrote prisma/mysql/schema.prisma");
}

function migration(name) {
  if (!name) throw new Error("Usage: node scripts/db-mysql.mjs migration <name>");
  sync();
  mkdirSync(migrations, { recursive: true });
  const prisma = path.join(root, "node_modules", "prisma", "build", "index.js");
  const args = ["migrate", "diff", "--to-schema", out, "--script"];
  if (existsSync(snapshot)) args.splice(2, 0, "--from-schema", snapshot);
  else args.splice(2, 0, "--from-empty");
  const sql = execFileSync(process.execPath, [prisma, ...args], {
    encoding: "utf8",
    env: { ...process.env, DATABASE_PROVIDER: "mysql" },
  });
  if (!sql.trim() || /This is an empty migration/.test(sql)) {
    console.log("No MySQL schema changes — nothing to write.");
    return;
  }
  const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
  const folder = path.join(migrations, `${stamp}_${name.replace(/\W+/g, "_")}`);
  mkdirSync(folder, { recursive: true });
  writeFileSync(path.join(folder, "migration.sql"), sql);
  writeFileSync(
    path.join(migrations, "migration_lock.toml"),
    '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "mysql"\n',
  );
  copyFileSync(out, snapshot);
  console.log(`✓ wrote ${path.relative(root, folder)}/migration.sql`);
}

const [cmd, arg] = process.argv.slice(2);
if (cmd === "sync") sync();
else if (cmd === "migration") migration(arg);
else {
  console.error("Usage: node scripts/db-mysql.mjs <sync|migration name>");
  process.exit(1);
}
